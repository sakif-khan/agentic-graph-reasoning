def main():
    d = json.load(io.open(NUMS, encoding="utf-8"))
    sysres = d["main_results"]["by_system"]
    hop = d["main_results"]["hop_trends"]["cwq"]["agr"]["hits_at_1"]
    t1 = d["groundedness_tier1_structural"]["both_agr"]

    budget = io.open(ROOT / "agr" / "budget.py", encoding="utf-8").read()
    calls = re.search(r"class BudgetConfig.*?max_llm_calls: int = (\d+)",
                      budget, re.S)
    assert calls, "max_llm_calls is not where it was in agr/budget.py"

    tests = json.load(io.open(ROOT / "results" / "phase4" / "test_webqsp.json",
                              encoding="utf-8"))
    q = next(r for r in tests if r["qid"] == EXAMPLE)
    assert len(q["gold_q_entities"]) == 1 and len(q["answers"]) == 1, \
        f"{EXAMPLE} is no longer the single-topic, single-gold example"

    # The strongest baseline is whichever it is, per dataset, rather than
    # a name written down here: an ablation that moved one would leave a
    # graphic quietly comparing against second place.
    def best(ds):
        return max(v["hits_at_1"] for k, v in sysres.items()
                   if k.startswith(ds + "/") and not k.endswith("/agr"))

    fields = {
        "QUESTION": q["question"],
        "TOPIC": q["gold_q_entities"][0],
        "GOLD": q["answers"][0],
        "QID": q["qid"],
        "CALLS": calls.group(1),
        "NQ": str(d["test_sets"]["webqsp"]["n_questions"]),
        "HWQ": f"{sysres['webqsp/agr']['hits_at_1']:.3f}",
        "HCWQ": f"{sysres['cwq/agr']['hits_at_1']:.3f}",
        "BWQ": f"{best('webqsp'):.3f}",
        "BCWQ": f"{best('cwq'):.3f}",
        "HEDGEWQ": f"{sysres['webqsp/agr']['hedge_pct']}",
        "HEDGECWQ": f"{sysres['cwq/agr']['hedge_pct']}",
        "H1": f"{hop[0]}", "H2": f"{hop[1]}", "H3": f"{hop[2]}",
        "UNG": f"{t1['entity_ungrounded_pct']}",
        "ASSERTED": f"{t1['entities_asserted']:,}",
        "DEFECTS": str(d["benchmark_defects"]["distinct_questions"]),
        "AT": "@",          # Hits@1 -- keeps the @@NAME@@ token syntax clean
    }

    tex = TEMPLATE
    for k, v in fields.items():
        tex = tex.replace(f"@@{k}@@", v)
    left = re.findall(r"@@\w+@@", tex)
    assert not left, f"unfilled placeholders: {sorted(set(left))}"

    io.open(HERE / "thumbnail.tex", "w", encoding="utf-8",
            newline="\n").write(tex.lstrip("\n"))

    r = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode",
                        "thumbnail.tex"], cwd=HERE,
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stdout[-3000:])
        return 1

    log = io.open(HERE / "thumbnail.log", encoding="utf-8",
                  errors="replace").read()
    bad = [l for l in log.splitlines() if "Overfull" in l or "Underfull" in l]
    for l in bad:
        print("  " + l)

    import pymupdf
    doc = pymupdf.open(HERE / "thumbnail.pdf")
    pix = doc[0].get_pixmap(dpi=DPI)
    pix.save(HERE / "thumbnail.png")
    print(f"thumbnail.png  {pix.width}x{pix.height}px at {DPI} dpi"
          + (f"   [{len(bad)} bad boxes]" if bad else "   [no bad boxes]"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
